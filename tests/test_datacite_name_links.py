"""Exercise DataCite matching with a scratch PostgreSQL database, never the live registry."""
import os
import uuid

import pytest
from sqlalchemy import create_engine, event, text
from sqlalchemy.engine import make_url
from sqlalchemy.pool import NullPool


@pytest.fixture
def registry(monkeypatch):
    url = os.environ.get("SOURCES_TEST_PG_URL")
    if not url:
        pytest.skip("set SOURCES_TEST_PG_URL to a scratch PostgreSQL database")
    parsed = make_url(url)
    if parsed.host not in ("127.0.0.1", "localhost", "::1"):
        pytest.fail("these tests require a loopback scratch database")
    schema = "datacite_test_" + uuid.uuid4().hex
    engine = create_engine(url, poolclass=NullPool)
    with engine.begin() as conn:
        conn.execute(text(f'CREATE SCHEMA "{schema}"'))

    @event.listens_for(engine, "connect")
    def set_schema(dbapi_connection, _):
        with dbapi_connection.cursor() as cursor:
            cursor.execute(f'SET search_path TO "{schema}"')
        dbapi_connection.commit()

    with engine.begin() as conn:
        conn.execute(text("""
            CREATE TABLE sources (
                id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                display_name text, type text, publisher text, publisher_id bigint,
                homepage_url text, country_code text, country text, issn_l text, crossref_id text,
                datacite_id text, datacite_ids jsonb DEFAULT '[]',
                updated_date timestamptz, is_oa boolean
            );
            CREATE TABLE source_issn (
                source_id bigint REFERENCES sources(id), issn text UNIQUE, is_issn_l boolean
            );
            CREATE TABLE issn_to_issnl (issn text, issn_l text);
            CREATE TABLE source_ingest_issue (
                source_feed text, issue_type text, matched_source_ids bigint[],
                issns text[], detail text, resolved_at timestamptz,
                UNIQUE(source_feed, issue_type, matched_source_ids)
            );
            CREATE TABLE source_datacite_id (
                datacite_id text PRIMARY KEY, source_id bigint REFERENCES sources(id)
            );
            CREATE TABLE datacite_client (
                id text PRIMARY KEY, display_name text, issns text[], url text,
                client_type text, provider_name text
            );
        """))
    monkeypatch.setenv("DATABASE_URL", url)
    from jobs import sync_datacite_clients as job
    monkeypatch.setattr(job, "engine", engine)
    try:
        yield engine, job
    finally:
        with engine.begin() as conn:
            conn.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
        engine.dispose()


def seed(engine, clients, *, source=True, linked=False, issn=False):
    with engine.begin() as conn:
        if source:
            conn.execute(text("INSERT INTO sources (id, display_name, type, publisher) "
                              "VALUES (1, 'Global Research Data Repository', 'repository', 'Research Consortium')"))
        if issn:
            conn.execute(text("INSERT INTO source_issn VALUES (1, '1234-5679', TRUE)"))
        if linked:
            conn.execute(text("INSERT INTO source_datacite_id VALUES ('a', 1)"))
        for client_id, client_issns in clients:
            conn.execute(text("INSERT INTO datacite_client VALUES "
                              "(:id, 'Global Research Data Repository', :issns, NULL, 'repository', 'Research Consortium')"),
                         {"id": client_id, "issns": client_issns})


def links(engine):
    with engine.connect() as conn:
        return dict(conn.execute(text("SELECT datacite_id, source_id FROM source_datacite_id ORDER BY datacite_id")).fetchall())


@pytest.mark.parametrize("batch", [1, 200])
def test_name_link_claims_source_for_later_clients_in_same_run(registry, batch):
    engine, job = registry
    seed(engine, [("a", []), ("b", [])])
    counts = job.run(batch=batch)
    result = links(engine)
    assert result["a"] == 1
    assert result["b"] != result["a"]
    assert counts["linked_by_name"] == 1
    assert counts["added"] == 1


def test_issn_link_also_excludes_source_from_later_name_only_matching(registry):
    engine, job = registry
    seed(engine, [("a", ["1234-5679"]), ("b", [])], issn=True)
    counts = job.run()
    assert links(engine)["a"] != links(engine)["b"]
    assert counts["linked_by_issn"] == 1
    assert counts["added"] == 1


def test_dry_run_models_name_candidate_claim_without_writing(registry):
    engine, job = registry
    seed(engine, [("a", []), ("b", [])])
    counts = job.run(dry_run=True)
    assert counts["linked_by_name"] == 1
    assert counts["added"] == 1
    assert links(engine) == {}


def test_source_linked_before_run_is_already_excluded(registry):
    engine, job = registry
    seed(engine, [("a", []), ("b", [])], linked=True)
    job.run()
    assert links(engine)["a"] != links(engine)["b"]


def test_strong_issn_evidence_can_still_link_two_clients_to_one_source(registry):
    engine, job = registry
    seed(engine, [("a", ["1234-5679"]), ("b", ["1234-5679"])], issn=True)
    job.run()
    assert links(engine) == {"a": 1, "b": 1}


def test_single_name_match_still_links(registry):
    engine, job = registry
    seed(engine, [("a", [])])
    job.run()
    assert links(engine) == {"a": 1}


def test_clients_arriving_in_separate_runs_keep_separate_sources(registry):
    engine, job = registry
    seed(engine, [("a", [])])
    job.run()
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO datacite_client VALUES "
                          "('b', 'Global Research Data Repository', '{}', NULL, 'repository', 'Research Consortium')"))
    job.run()
    assert links(engine)["a"] != links(engine)["b"]


def test_newly_minted_clients_are_not_name_candidates(registry):
    engine, job = registry
    seed(engine, [("a", []), ("b", [])], source=False)
    job.run()
    assert links(engine)["a"] != links(engine)["b"]
